#include "etc1.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define CHECK(c) do { if (!(c)) { fprintf(stderr, "%s:%d: %s\n", __FILE__, __LINE__, #c); exit(1); } } while (0)

static void put32(uint8_t *data, uint32_t value)
{
    for (unsigned i = 0; i < 4; ++i) data[i] = (uint8_t)(value >> (8 * i));
}

static void color_block(uint8_t data[8], uint32_t high, uint32_t selectors)
{
    /* PICA stores the whole ETC word little-endian, including selector planes. */
    put32(data, selectors);
    put32(data + 4, high);
}

static void pixel(const uint8_t rgba[64], unsigned x, unsigned y,
                   unsigned r, unsigned g, unsigned b, unsigned a)
{
    const uint8_t *p = rgba + 4 * (4 * y + x);
    CHECK(p[0] == r && p[1] == g && p[2] == b && p[3] == a);
}

static void test_individual_and_partition(void)
{
    /* Literal PICA bytes: individual R=(1,8), G=(2,9), B=(3,10), both
     * modifier tables zero; selectors zero add two to each component. */
    uint8_t data[8] = {0,0,0,0, 0,0x3a,0x29,0x18};
    uint8_t rgba[64];
    for (unsigned flip = 0; flip < 2; ++flip) {
        data[4] = (uint8_t)flip;
        CHECK(px_etc1_decode_block(data, 8, 0, rgba, sizeof rgba) == PX_ETC1_OK);
        for (unsigned y = 0; y < 4; ++y)
            for (unsigned x = 0; x < 4; ++x) {
                const unsigned second = flip ? y >= 2 : x >= 2;
                pixel(rgba, x, y, second ? 138 : 19, second ? 155 : 36,
                      second ? 172 : 53, 255);
            }
        /* Different table fields must affect only their own subblock. */
        color_block(data, UINT32_C(0x284a6c38) | flip, 0);
        CHECK(px_etc1_decode_block(data, 8, 0, rgba, sizeof rgba) == PX_ETC1_OK);
        for (unsigned y = 0; y < 4; ++y)
            for (unsigned x = 0; x < 4; ++x) {
                const unsigned second = flip ? y >= 2 : x >= 2;
                pixel(rgba, x, y, second ? 169 : 39, second ? 203 : 73,
                      second ? 237 : 107, 255);
            }
        data[5] = 0x3a; data[6] = 0x29; data[7] = 0x18;
    }
}

static void test_modifiers_and_selectors(void)
{
    /* Fixed expected results for base color (119,119,119), including both
     * saturation directions. These are not generated by another decoder. */
    static const uint8_t expected[8][4] = {
        {121,127,117,111}, {124,136,114,102}, {128,148,110,90},
        {132,161,106,77}, {137,179,101,59}, {143,199,95,39},
        {152,225,86,13}, {166,255,72,0}
    };
    uint8_t data[8], rgba[64];
    for (unsigned table = 0; table < 8; ++table)
        for (unsigned selector = 0; selector < 4; ++selector)
            for (unsigned flip = 0; flip < 2; ++flip) {
                uint32_t planes = (selector & 1 ? UINT32_C(0x0000ffff) : 0) |
                                  (selector & 2 ? UINT32_C(0xffff0000) : 0);
                color_block(data, UINT32_C(0x77777700) | table << 5 | table << 2 | flip, planes);
                CHECK(px_etc1_decode_block(data, 8, 0, rgba, sizeof rgba) == PX_ETC1_OK);
                for (unsigned p = 0; p < 16; ++p)
                    pixel(rgba, p % 4, p / 4, expected[table][selector],
                          expected[table][selector], expected[table][selector], 255);
            }
    static const uint8_t positions[16][2] = {
        {0,0},{0,1},{0,2},{0,3}, {1,0},{1,1},{1,2},{1,3},
        {2,0},{2,1},{2,2},{2,3}, {3,0},{3,1},{3,2},{3,3}
    };
    for (unsigned bit = 0; bit < 16; ++bit)
        for (unsigned selector = 1; selector < 4; ++selector) {
            uint32_t planes = (selector & 1 ? UINT32_C(1) << bit : 0) |
                              (selector & 2 ? UINT32_C(1) << (bit + 16) : 0);
            color_block(data, UINT32_C(0x77777700), planes);
            CHECK(px_etc1_decode_block(data, 8, 0, rgba, sizeof rgba) == PX_ETC1_OK);
            for (unsigned y = 0; y < 4; ++y)
                for (unsigned x = 0; x < 4; ++x) {
                    const uint8_t value = x == positions[bit][0] && y == positions[bit][1] ?
                                          expected[0][selector] : 121;
                    pixel(rgba, x, y, value, value, value, 255);
                }
        }
}

static void test_differential(void)
{
    uint8_t data[8], rgba[64];
    for (unsigned flip = 0; flip < 2; ++flip) {
        /* Five-bit bases (28,4,3), signed deltas (-4,+2,0). */
        color_block(data, UINT32_C(0xe4221802) | flip, 0);
        CHECK(px_etc1_decode_block(data, 8, 0, rgba, sizeof rgba) == PX_ETC1_OK);
        for (unsigned y = 0; y < 4; ++y)
            for (unsigned x = 0; x < 4; ++x) {
                const unsigned second = flip ? y >= 2 : x >= 2;
                pixel(rgba, x, y, second ? 200 : 233, second ? 51 : 35, 26, 255);
            }
    }
    static const uint8_t second_color[8] = {125,134,142,150,92,101,109,117};
    for (unsigned delta = 0; delta < 8; ++delta) {
        color_block(data, UINT32_C(0x78787802) | delta << 24 | delta << 16 | delta << 8, 0);
        CHECK(px_etc1_decode_block(data, 8, 0, rgba, sizeof rgba) == PX_ETC1_OK);
        pixel(rgba, 0, 0, 125,125,125,255);
        pixel(rgba, 2, 0, second_color[delta],second_color[delta],second_color[delta],255);
    }
    static const uint8_t expanded[32] = {
        0,8,16,24,33,41,49,57,66,74,82,90,99,107,115,123,
        132,140,148,156,165,173,181,189,198,206,214,222,231,239,247,255
    };
    for (unsigned base = 0; base < 32; ++base) {
        color_block(data, base << 27 | base << 19 | base << 11 | 2, 0);
        CHECK(px_etc1_decode_block(data, 8, 0, rgba, sizeof rgba) == PX_ETC1_OK);
        unsigned value = base == 31 ? 255 : (unsigned)expanded[base] + 2;
        for (unsigned p = 0; p < 16; ++p) pixel(rgba, p % 4, p / 4, value,value,value,255);
    }
}

static void test_alpha(void)
{
    /* Nibbles 0..15 are column-major within a PICA 4x4 block. */
    uint8_t data[16] = {0x10,0x32,0x54,0x76,0x98,0xba,0xdc,0xfe};
    color_block(data + 8, UINT32_C(0x77777700), 0);
    uint8_t guarded[66]; memset(guarded, 0xa5, sizeof guarded);
    CHECK(px_etc1_decode_block(data, 16, 1, guarded + 1, 64) == PX_ETC1_OK);
    CHECK(guarded[0] == 0xa5 && guarded[65] == 0xa5);
    static const uint8_t alpha[4][4] = {
        {0,68,136,204}, {17,85,153,221}, {34,102,170,238}, {51,119,187,255}
    };
    for (unsigned y = 0; y < 4; ++y)
        for (unsigned x = 0; x < 4; ++x) pixel(guarded + 1,x,y,121,121,121,alpha[y][x]);
    memset(data, 0, 8);
    CHECK(px_etc1_decode_block(data, 16, 1, guarded + 1, 64) == PX_ETC1_OK);
    for (unsigned p = 0; p < 16; ++p) pixel(guarded + 1,p%4,p/4,121,121,121,0);
    memset(data, 255, 8);
    CHECK(px_etc1_decode_block(data, 16, 1, guarded + 1, 64) == PX_ETC1_OK);
    for (unsigned p = 0; p < 16; ++p) pixel(guarded + 1,p%4,p/4,121,121,121,255);
}

static void rejects(const uint8_t *data, size_t size, int alpha, size_t capacity,
                     enum px_etc1_result result)
{
    uint8_t rgba[64], unchanged[64]; memset(rgba, 0xa5, sizeof rgba);
    memcpy(unchanged, rgba, sizeof rgba);
    CHECK(px_etc1_decode_block(data, size, alpha, rgba, capacity) == result);
    CHECK(memcmp(rgba, unchanged, sizeof rgba) == 0);
}

static void test_errors(void)
{
    uint8_t data[16] = {0};
    rejects(NULL,8,0,64,PX_ETC1_INVALID_ARGUMENT);
    CHECK(px_etc1_decode_block(data,8,0,NULL,64) == PX_ETC1_INVALID_ARGUMENT);
    rejects(data,16,2,64,PX_ETC1_INVALID_ARGUMENT);
    rejects(data,16,-1,64,PX_ETC1_INVALID_ARGUMENT);
    for (unsigned alpha = 0; alpha < 2; ++alpha) {
        for (size_t size = 0; size < (alpha ? 16u : 8u); ++size)
            rejects(data,size,(int)alpha,64,PX_ETC1_TRUNCATED);
        for (size_t capacity = 0; capacity < 64; ++capacity)
            rejects(data,16,(int)alpha,capacity,PX_ETC1_OUTPUT_TOO_SMALL);
    }
    /* Reject differential under/overflow in each channel, including cases
     * that ETC2 could assign another meaning. No silent wrap or extension. */
    for (unsigned channel = 0; channel < 3; ++channel)
        for (unsigned over = 0; over < 2; ++over)
            for (unsigned flip = 0; flip < 2; ++flip) {
                unsigned shift = 24 - 8 * channel;
                uint32_t high = UINT32_C(0x78787802) & ~(UINT32_C(0xff) << shift);
                high |= (over ? UINT32_C(0xf9) : UINT32_C(0x07)) << shift;
                color_block(data, high | flip, 0);
                rejects(data,8,0,64,PX_ETC1_UNSUPPORTED_BLOCK);
                memcpy(data + 8, data, 8);
                rejects(data,16,1,64,PX_ETC1_UNSUPPORTED_BLOCK);
            }
}

int main(void)
{
    test_individual_and_partition();
    test_modifiers_and_selectors();
    test_differential();
    test_alpha();
    test_errors();
    puts("PASS: ETC1 fixed individual/differential vectors, all modifier/selector bits, PICA alpha order, bounds and ETC2 rejection");
    return 0;
}
